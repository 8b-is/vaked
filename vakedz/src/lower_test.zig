// _nix_str / _nix_attr_key — the #7 splice class. These are the injection
// guard: a host-controlled name must never be able to break out of a Nix
// string literal or splice into a NESTED attrpath. Python neutralizes the
// three active sequences with CHAINED replaces (backslash FIRST, then `"`,
// then `${`); lower.zig does it in one pass, so the equivalence of the two is
// worth pinning explicitly -- the fixtures never exercise any of it.
//
// Expectations generated from the reference:
//   >>> lower._nix_str(s)
// --------------------------------------------------------------------------

test "lower: nixStr neutralizes backslash, quote and antiquotation" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();

    const cases = [_]struct { in: []const u8, want: []const u8 }{
        .{ .in = "plain", .want = "\"plain\"" },
        .{ .in = "a\\b", .want = "\"a\\\\b\"" },
        .{ .in = "q\"r", .want = "\"q\\\"r\"" },
        .{ .in = "x${y}", .want = "\"x\\${y}\"" },
        // backslash escaped FIRST, so the `${` guard's own backslash survives
        .{ .in = "back\\${z}", .want = "\"back\\\\\\${z}\"" },
        // a bare `$` is only active when followed by `{`
        .{ .in = "$notbrace", .want = "\"$notbrace\"" },
        .{ .in = "trail$", .want = "\"trail$\"" },
    };
    for (cases) |c| {
        try std.testing.expectEqualStrings(c.want, try lower.nixStr(a, c.in));
    }
}

