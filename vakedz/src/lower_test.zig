// enrich_graph: the fiber `policy { ... }` sub-block the minimal resolver drops
// must be recovered, or the RUNTIME.md Policy column silently renders as an
// em-dash (and the fiber's inputsHash changes). The golden above already pins
// this end-to-end; this test isolates the mechanism.
