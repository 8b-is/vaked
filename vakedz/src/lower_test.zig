const std = @import("std");
const testing = std.testing;
const lib = @import("lib");
const lex = @import("lexer.zig");
const parser = @import("parser.zig");
const resolve = @import("resolve.zig");
const lower = @import("lower.zig");

fn parseItems(a: std.mem.Allocator, src: []const u8) ![]const parser.Item {
    var l = lex.Lexer.init(a, src);
    try l.run();
    try testing.expectEqual(@as(usize, 0), l.errors.items.len);
    var p = parser.Parser.init(a, l.tokens.items);
    return p.parseFile();
}

/// The exact driver order of `vakedc lower`: parse -> build_graph -> lower
/// (which runs enrich_graph first when items are supplied).
fn lowerSource(a: std.mem.Allocator, src: []const u8, filename: []const u8) !lower.LowerResult {
    const items = try parseItems(a, src);
    var res = try resolve.buildGraph(a, items, filename);
    return lower.lower(a, &res.graph, filename, items);
}

fn fileContent(result: lower.LowerResult, path: []const u8) ?[]const u8 {
    for (result.files) |f| {
        if (std.mem.eql(u8, f.path, path)) return f.content;
    }
    return null;
}

