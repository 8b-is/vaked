test "lower: enrichGraph attaches a fiber's policy config block" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();

    const items = try parseItems(a, operator_field_src);
    var res = try resolve.buildGraph(a, items, fixture_path);

    // Before enrichment the resolver has dropped `policy { ... }` entirely.
    const fiber_id = "operator-field.vaked#operator-field/mediaCompress";
    const before = res.graph.getNode(fiber_id) orelse return error.TestUnexpectedResult;
    try std.testing.expect(propOf(before.props, "policy") == null);

    try lower.enrichGraph(a, &res.graph, items);

    const after = res.graph.getNode(fiber_id) orelse return error.TestUnexpectedResult;
    const policy = propOf(after.props, "policy") orelse return error.TestUnexpectedResult;
    // It lands as a record-carrying app value: {"ref":"policy","record":[...]}
    try std.testing.expect(propOf(policy, "record") != null);

    // Idempotent: a second pass must not duplicate or replace the prop.
    const n_before = countEntries(after.props);
    try lower.enrichGraph(a, &res.graph, items);
    const again = res.graph.getNode(fiber_id) orelse return error.TestUnexpectedResult;
    try std.testing.expectEqual(n_before, countEntries(again.props));
}

fn propOf(v: lib.json.Value, key: []const u8) ?lib.json.Value {
    switch (v) {
        .object => |obj| {
            for (obj) |e| {
                if (std.mem.eql(u8, e.key, key)) return e.value;
            }
            return null;
        },
        else => return null,
    }
}

fn countEntries(v: lib.json.Value) usize {
    return switch (v) {
        .object => |obj| obj.len,
        else => 0,
    };
}

